// Reads ideas/*.md frontmatter and writes GRAPH.md: a Mermaid dependency graph,
// what is ready to start, what is blocked and on what. `--check` only validates.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const STATUSES = ['idea', 'fleshed-out', 'ready', 'in-progress', 'done', 'dropped'] as const;
type Status = (typeof STATUSES)[number];

interface Idea {
  id: string;
  title: string;
  status: Status;
  area: string;
  size: string;
  dependsOn: string[];
  file: string;
}

const root = join(import.meta.dir, '..');
const ideasDir = join(root, 'ideas');

function parseFrontmatter(file: string, text: string): Record<string, string> {
  const match = text.match(/^---\n([\s\S]*?)\n---/);
  if (!match) throw new Error(`${file}: missing frontmatter`);
  const fields: Record<string, string> = {};
  for (const line of match[1].split('\n')) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (kv) fields[kv[1]] = kv[2].trim();
  }
  return fields;
}

function parseList(value: string | undefined): string[] {
  if (!value || value === '[]') return [];
  return value.replace(/^\[|\]$/g, '').split(',').map((s) => s.trim()).filter(Boolean);
}

function loadIdeas(): { ideas: Idea[]; problems: string[] } {
  const problems: string[] = [];
  const ideas: Idea[] = [];
  for (const file of readdirSync(ideasDir).filter((f) => f.endsWith('.md')).sort()) {
    const fields = parseFrontmatter(file, readFileSync(join(ideasDir, file), 'utf8'));
    const id = file.replace(/\.md$/, '');
    if (fields.id !== id) problems.push(`${file}: id "${fields.id}" must match the file name`);
    if (!STATUSES.includes(fields.status as Status)) problems.push(`${file}: unknown status "${fields.status}"`);
    ideas.push({
      id,
      title: fields.title ?? id,
      status: fields.status as Status,
      area: fields.area ?? '',
      size: fields.size ?? '?',
      dependsOn: parseList(fields.depends_on),
      file,
    });
  }
  const ids = new Set(ideas.map((i) => i.id));
  for (const idea of ideas) {
    for (const dep of idea.dependsOn) {
      if (!ids.has(dep)) problems.push(`${idea.file}: depends on missing idea "${dep}"`);
    }
  }
  problems.push(...findCycles(ideas));
  return { ideas, problems };
}

function findCycles(ideas: Idea[]): string[] {
  const byId = new Map(ideas.map((i) => [i.id, i]));
  const state = new Map<string, 'visiting' | 'done'>();
  const cycles: string[] = [];
  const visit = (id: string, path: string[]) => {
    if (state.get(id) === 'done') return;
    if (state.get(id) === 'visiting') {
      cycles.push(`cycle: ${[...path.slice(path.indexOf(id)), id].join(' → ')}`);
      return;
    }
    state.set(id, 'visiting');
    for (const dep of byId.get(id)?.dependsOn ?? []) if (byId.has(dep)) visit(dep, [...path, id]);
    state.set(id, 'done');
  };
  for (const idea of ideas) visit(idea.id, []);
  return cycles;
}

function render(ideas: Idea[]): string {
  const byId = new Map(ideas.map((i) => [i.id, i]));
  const live = ideas.filter((i) => i.status !== 'dropped');
  const open = live.filter((i) => i.status !== 'done' && i.status !== 'in-progress');
  const blockers = (i: Idea) => i.dependsOn.filter((d) => byId.get(d)?.status !== 'done');
  const ready = open.filter((i) => blockers(i).length === 0);
  const blocked = open.filter((i) => blockers(i).length > 0);
  const inProgress = live.filter((i) => i.status === 'in-progress');
  const link = (i: Idea) => `[${i.title}](ideas/${i.file})`;

  const node = (i: Idea) => `  ${i.id.replace(/-/g, '_')}["${i.title.replace(/"/g, "'")}"]:::${i.status.replace('-', '_')}`;
  const edges = live.flatMap((i) =>
    i.dependsOn.filter((d) => byId.get(d)?.status !== 'dropped').map((d) => `  ${d.replace(/-/g, '_')} --> ${i.id.replace(/-/g, '_')}`),
  );

  return [
    '# Roadmap graph',
    '',
    '_Generated by `bun scripts/graph.ts` — do not edit by hand._ Arrows point from a dependency to what it unblocks.',
    '',
    '```mermaid',
    'flowchart LR',
    ...live.map(node),
    ...edges,
    '  classDef idea fill:#eee,stroke:#999',
    '  classDef fleshed_out fill:#e8f0fe,stroke:#6b8fd6',
    '  classDef ready fill:#fff4d6,stroke:#d6a400',
    '  classDef in_progress fill:#ffe0c2,stroke:#e07b00',
    '  classDef done fill:#d8f5d8,stroke:#3a9a3a',
    '```',
    '',
    '## In progress',
    '',
    ...(inProgress.length ? inProgress.map((i) => `- ${link(i)} — ${i.area}, ${i.size}`) : ['_Nothing._']),
    '',
    '## Ready to start (every dependency done)',
    '',
    ...(ready.length ? ready.map((i) => `- ${link(i)} — ${i.status}, ${i.area}, ${i.size}`) : ['_Nothing._']),
    '',
    '## Blocked',
    '',
    ...(blocked.length
      ? blocked.map((i) => `- ${link(i)} — waiting on ${blockers(i).map((d) => byId.get(d)?.title ?? d).join(', ')}`)
      : ['_Nothing._']),
    '',
    '## Done',
    '',
    ...(live.some((i) => i.status === 'done') ? live.filter((i) => i.status === 'done').map((i) => `- ${link(i)}`) : ['_Nothing yet._']),
    '',
  ].join('\n');
}

const { ideas, problems } = loadIdeas();
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
if (!process.argv.includes('--check')) {
  writeFileSync(join(root, 'GRAPH.md'), render(ideas));
  console.log(`GRAPH.md: ${ideas.length} ideas`);
}
